--   - popup_id 생성 방식: 엔티티는 IDENTITY. 실제가 bigserial 인지 GENERATED ... AS IDENTITY 인지 모름.
--   - UNIQUE (source, external_id): 코드가 전제하는 알려진 제약. 이름(popup_source_external_id_key)은 추정.
--   - view_count DEFAULT 0: 알려진 제약. 엔티티는 INSERT 에서 이 컬럼을 빼므로 DEFAULT 가 반드시 있어야 한다.
--   - FK interest_category_id → interest_category, area_id → favorite_area: 주석상 FK 로 쓰지만 실제 제약 유무 · ON DELETE 동작 모름.
--   - CHECK (source · reservation_type · place_resolution 값 목록): Hibernate 가 enum 으로 생성하는 제약. 실제 DB 에 있는지 모름.
--   - 인덱스: 엔티티에 선언이 없다. 실제 DB 의 인덱스(예: end_date, enriched_at, 좌표) 확인 필요.
--   - created_at · last_modified_at 의 DEFAULT: 엔티티(BaseEntity · JPA Auditing)가 채우므로 DB DEFAULT 유무는 모름.
--
-- #28 추가 컬럼(운영 DB 에는 아래 ALTER 로 적용)
