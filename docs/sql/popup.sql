CREATE TABLE popup (
    popup_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 최초 생성 원천(KAKAO_MAP · PERPLEXITY)
    source               varchar(255)  NOT NULL,
    -- 원천 측 식별자. 카카오는 place id, Perplexity 는 NULL
    external_id          varchar(255),
    -- 정보 근거 URL 목록(병합 시 합집합)
    source_urls          text[],
    -- 마지막으로 받은 원천 응답 원문
    raw_payload          jsonb,
    title                varchar(500)  NOT NULL,
    brand                varchar(500),
    interest_category_id integer,
    area_id              integer,
    description          text,
    tags                 text[],
    -- 대표 이미지 URL 목록(image 단계가 채운다. URL 만 저장)
    image_urls           text[],
    -- 마지막 이미지 수집 시도 시각(못 찾은 경우에도 갱신)
    image_checked_at     timestamptz,
    start_date           date,
    end_date             date,
    opening_hours        text,
    -- NONE · RESERVATION · WAITING · BOTH · UNKNOWN
    reservation_type     varchar(255)  NOT NULL,
    reservation_url      varchar(2000),
    reservation_open_at  timestamptz,
    entry_fee            integer,
    place_id             varchar(255),
    place_name           varchar(255),
    address_road         varchar(255),
    address_jibun        varchar(255),
    latitude             double precision,
    longitude            double precision,
    -- EXACT · VENUE · UNRESOLVED
    place_resolution     varchar(255),
    enrich_retry_count   integer       NOT NULL,
    enriched_at          timestamptz,
    -- 카카오 키워드 검색에서 마지막으로 발견된 시각(기록만 한다)
    last_seen_at         timestamptz,
    view_count           bigint        NOT NULL DEFAULT 0,
    created_at           timestamp(6)  NOT NULL,
    last_modified_at     timestamp(6)  NOT NULL,

    CONSTRAINT popup_source_external_id_key UNIQUE (source, external_id),
    CONSTRAINT popup_source_check CHECK (source IN ('KAKAO_MAP', 'PERPLEXITY')),
    CONSTRAINT popup_reservation_type_check CHECK (reservation_type IN ('NONE', 'RESERVATION', 'WAITING', 'BOTH', 'UNKNOWN')),
    CONSTRAINT popup_place_resolution_check CHECK (place_resolution IN ('EXACT', 'VENUE', 'UNRESOLVED'))
);
